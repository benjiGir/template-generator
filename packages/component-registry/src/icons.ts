/** Icônes par nom, tel qu'il est stocké dans les props de type `icon` */
export const ICONS: ReadonlyMap<string, LucideIcon> = new Map(Object.entries(ICON_SET));

/** Noms proposés dans le sélecteur, par ordre alphabétique */
export const ICON_NAMES: readonly string[] = Object.keys(ICON_SET);

/** Icône désignée par son nom ; l'icône de repli si le nom est inconnu */
export function IconByName({ name, fallback, ...props }: LucideProps & { name: string; fallback: LucideIcon }) {
  return createElement(ICONS.get(name) ?? fallback, props);
}
